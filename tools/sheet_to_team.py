#!/usr/bin/env python3
"""Convert the "Members" tab of the OSiV Team Profiles sheet into osiv/data/team.js.

Usage:
    # Google Sheet → File → Download → Comma-separated values (.csv), with the "Members" tab selected
    python3 osiv/tools/sheet_to_team.py ~/Downloads/members.csv > osiv/data/team.js

Rows are skipped when "Show (Y/N)" is N or the member chose "I do not agree".
"Web group" decides the section on the team page (lead / research / media / design / advisor);
when it is empty the group is guessed from "Division". Google Drive photo links are turned into direct image links.
"""
import csv
import json
import re
import sys
import unicodedata
import urllib.parse

GROUPS = [
    {"id": "lead", "title": "Leadership"},
    {"id": "research", "title": "Research",
     "note": "Research division: scientific papers, provincial science and technology proposals, core technology."},
    {"id": "media", "title": "Media, Events & Partnerships",
     "note": "Operations division: communication, events, workshops and partnerships."},
    {"id": "design", "title": "Design"},
    {"id": "advisor", "title": "Advisors"},
]

FIELDS = {  # team.js key -> sheet column
    "role": "Role",
    "research": "Research interests",
    "edu": "Degree & affiliation",
    "photo": "Photo link",
    "web": "Website",
    "scholar": "Google Scholar",
    "linkedin": "LinkedIn",
    "orcid": "ORCID",
    "github": "GitHub",
    "researchgate": "ResearchGate",
    "facebook": "Facebook",
    "profile": "OSiV profile page",
}


def fold(s):
    s = unicodedata.normalize("NFD", s or "").lower()
    return "".join(c for c in s if unicodedata.category(c) != "Mn").replace("đ", "d")

JUNK = {"", "n/a", "na", "no", "none", "-", "khong", "khong co", "chua co"}
LINK_KEYS = {"web", "scholar", "linkedin", "orcid", "github", "researchgate", "facebook", "photo"}


def clean(key, v):
    """Drop placeholder answers ("N/A", "chua co", ...) and anything in a link field that is not a link."""
    v = (v or "").strip()
    f = fold(v).strip(" .!?")
    if f in JUNK or f.startswith(("ch co", "chua co", "tam thoi", "khong")) or f == "anything":
        return ""
    if key not in LINK_KEYS:
        return v
    if key == "orcid":
        m = re.search(r"\d{4}-\d{4}-\d{4}-\d{3}[\dX]", v)
        return f"https://orcid.org/{m.group(0)}" if m else ""
    if re.match(r"^(www\.|[a-z0-9-]+\.[a-z]{2,}/)", v, re.I):
        v = "https://" + v
    if not re.match(r"^https?://\S+$", v):
        return ""
    v = re.sub(r"[?&]utm_[^#]*", "", v)          # drop share-tracking parameters
    return urllib.parse.quote(v, safe=":/?#[]@!$&'()*+,;=%")


def guess_group(ban, explicit):
    g = (explicit or "").strip().lower()
    if g in {x["id"] for x in GROUPS}:
        return g
    b = fold(ban)
    if "leadership" in b:
        return "lead"
    if "advisor" in b:
        return "advisor"
    if "design" in b:
        return "design"
    if "operations" in b or "media" in b or "event" in b or "partner" in b:
        return "media"
    return "research"


def drive_image(url):
    m = re.search(r"drive\.google\.com/(?:file/d/|open\?id=|uc\?(?:.*&)?id=)([\w-]{20,})", url or "")
    return f"https://drive.google.com/thumbnail?id={m.group(1)}&sz=w1200" if m else (url or "")


def main(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    team = []
    for r in rows:
        r = {k.strip(): (v or "").strip() for k, v in r.items() if k}
        name = r.get("Display name") or r.get("Full name")
        if not name:
            continue
        if r.get("Show (Y/N)", "").upper().startswith("N"):
            continue
        if "not" in fold(r.get("Public display consent", "")):
            continue
        m = {"name": name, "group": guess_group(r.get("Division", ""), r.get("Web group"))}
        for key, col in FIELDS.items():
            v = clean(key, r.get(col, ""))
            if v:
                m[key] = v
        if "photo" in m:
            m["photo"] = drive_image(m["photo"])
        team.append(m)

    out = ["/* OSiV team data — generated by osiv/tools/sheet_to_team.py from the Team Profiles sheet. */", ""]
    out.append("window.OSIV_GROUPS = " + json.dumps(GROUPS, ensure_ascii=False, indent=2) + ";")
    out.append("")
    out.append("window.OSIV_TEAM = [")
    out.append(",\n".join("  " + json.dumps(m, ensure_ascii=False) for m in team))
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
